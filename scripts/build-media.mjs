import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir, readdir, stat } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { dirname, resolve, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import ffmpeg from "ffmpeg-static";
import { analyzeMusic, playbackBeats } from "../frontend/src/components/musicBeats.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = resolve(root, "frontend/public");
const output = resolve(publicDir, "media");
await mkdir(output, { recursive: true });
const images = [
  "LOGO.png",
  "mainBackground.jpg",
  "cow.png",
  ...["red", "yellow", "blue", "purple"].map((c) => `player_${c}.png`),
  "characters/farmers-v1.png",
  "characters/mothership-v1.png",
];
const inputs = [
  ...images.map((f) => `/images/${f}`),
  ...["menu", "lobby", "game"].map((t) => `/sounds/bgm/${t}-music.mp3`),
  ...(await readdir(resolve(publicDir, "sounds/sound-effects"))).map(
    (f) => `/sounds/sound-effects/${f}`,
  ),
];
const timingVersion = createHash('sha256').update(await readFile(resolve(root, 'frontend/src/components/musicBeats.ts'))).digest('hex').slice(0, 12);
const manifest = {};
const beats = {};
let before = 0,
  after = 0;
for (const path of inputs) {
  const source = await readFile(publicDir + path);
  const image = path.startsWith("/images/");
  const music = path.startsWith("/sounds/bgm/");
  const extension = image ? ".webp" : music ? ".webm" : extname(path);
  const hash = createHash("sha256")
    .update("media-v1-lossless-webp-opus96\0")
    .update(source)
    .digest("hex")
    .slice(0, 16);
  const name = `${basename(path, extname(path))}.${hash}${extension}`;
  const target = resolve(output, name);
  try {
    await stat(target);
  } catch {
    if (image)
      await sharp(source).webp({ lossless: true, effort: 6 }).toFile(target);
    else if (music) {
      const result = spawnSync(
        ffmpeg,
        [
          "-hide_banner",
          "-loglevel",
          "error",
          "-y",
          "-i",
          publicDir + path,
          "-map_metadata",
          "-1",
          "-vn",
          "-c:a",
          "libopus",
          "-b:a",
          "96k",
          "-vbr",
          "on",
          "-application",
          "audio",
          target,
        ],
        { encoding: "utf8" },
      );
      if (result.status !== 0)
        throw Error(
          result.stderr || result.error?.message || "Audio encoding failed",
        );
    } else await writeFile(target, source);
  }
  // A lossless conversion can be larger than an already optimized source JPEG.
  const larger = (await stat(target)).size > source.length;
  const chosenName = larger
    ? `${basename(path, extname(path))}.${hash}${extname(path)}`
    : name;
  if (larger) await writeFile(resolve(output, chosenName), source);
  manifest[path] = `/media/${chosenName}`;
  before += source.length;
  after += (await stat(resolve(output, chosenName))).size;
  if (music) {
    const track = basename(path).replace('-music.mp3', '');
    const cache = resolve(output, `${hash}.${timingVersion}.beats.json`);
    try { beats[track] = JSON.parse(await readFile(cache, 'utf8')); }
    catch {
      const decoded = spawnSync(ffmpeg, ['-v', 'error', '-i', publicDir + path, '-af', 'pan=mono|c0=c0', '-ar', '48000', '-f', 'f32le', 'pipe:1'], {maxBuffer: 32 * 1024 * 1024});
      if (decoded.status !== 0) throw Error(decoded.stderr.toString() || 'Beat analysis decode failed');
      const pcm = decoded.stdout;
      const samples = new Float32Array(pcm.buffer.slice(pcm.byteOffset, pcm.byteOffset + pcm.length));
      beats[track] = playbackBeats(track, analyzeMusic(samples, 48000));
      await writeFile(cache, JSON.stringify(beats[track]));
    }
  }
}
await writeFile(
  resolve(root, "frontend/src/media-manifest.ts"),
  `// Generated by scripts/build-media.mjs. Original art remains in public/images.\nexport default ${JSON.stringify(
    manifest,
    null,
    4,
  )} as Record<string, string>;\nexport const beatGrids = ${JSON.stringify(beats)};\n`,
);
const css = [
  ":root {",
  ...[
    "mainBackground.jpg",
    ...["red", "yellow", "blue", "purple"].map((c) => `player_${c}.png`),
  ].map(
    (f, i) =>
      `  --media-${
        i === 0 ? "background" : ["red", "yellow", "blue", "purple"][i - 1]
      }: url("${manifest["/images/" + f]}");`,
  ),
  "}",
].join("\n");
await writeFile(resolve(root, "frontend/src/media.css"), css + "\n");
console.log(
  `Media: ${inputs.length} files, ${(before / 1024 / 1024).toFixed(2)} → ${(
    after /
    1024 /
    1024
  ).toFixed(2)} MiB (${Math.round(
    (1 - after / before) * 100,
  )}% smaller). Cached outputs are reused.`,
);
