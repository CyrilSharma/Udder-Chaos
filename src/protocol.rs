use crate::game::{GameView, Move, Rules};
use serde::{Deserialize, Serialize};
use ts_rs::TS;
pub const VERSION: u32 = 1;
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
#[serde(deny_unknown_fields)]
pub struct Settings {
    pub seed: u32,
    pub map_id: usize,
    pub card_deck_size: usize,
    pub timer_length: u32,
    pub difficulty: u32,
    pub threads: usize,
    pub rules: Rules,
}
impl Default for Settings {
    fn default() -> Self {
        Self {
            seed: 0,
            map_id: 0,
            card_deck_size: 15,
            timer_length: 30,
            difficulty: 1000,
            threads: 1,
            rules: Rules::default(),
        }
    }
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct Player {
    pub name: String,
    pub color: u8,
    pub connected: bool,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct Snapshot {
    pub version: u32,
    pub room: String,
    pub revision: u32,
    pub players: Vec<Player>,
    pub settings: Settings,
    pub game: Option<GameView>,
    pub frames: Vec<GameView>,
    pub you: u8,
    pub host: bool,
    pub solo: bool,
    pub turn_deadline_ms: f64,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum Command {
    Create {
        name: String,
        solo: bool,
        settings: Settings,
    },
    Join {
        room: String,
        name: String,
        token: Option<String>,
    },
    Rejoin {
        room: String,
        name: Option<String>,
    },
    Get {
        room: String,
        token: String,
    },
    Configure {
        room: String,
        token: String,
        name: String,
        color: u8,
        settings: Option<Settings>,
        solo: Option<bool>,
    },
    Start {
        room: String,
        token: String,
    },
    Move {
        room: String,
        token: String,
        revision: u32,
        action: Move,
    },
    Leave {
        room: String,
        token: String,
    },
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct Reply {
    pub snapshot: Option<Snapshot>,
    pub token: Option<String>,
    pub error: Option<String>,
}
impl Reply {
    pub fn error(s: impl Into<String>) -> Self {
        Self {
            snapshot: None,
            token: None,
            error: Some(s.into()),
        }
    }
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
#[serde(deny_unknown_fields)]
pub struct PreviewRequest {
    pub room: String,
    pub token: String,
    pub revision: u32,
    pub card: usize,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct CardPreview {
    pub revision: u32,
    pub card: usize,
    pub steps: Vec<Vec<crate::game::Piece>>,
}
#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct PreviewReply {
    pub preview: Option<CardPreview>,
    pub error: Option<String>,
}
pub fn typescript() -> String {
    let mut s = String::from("// Generated by cargo run --bin export-types. Do not edit.\n");
    macro_rules! emit {($($t:ty),*)=>{$(s.push_str("export ");s.push_str(&<$t>::decl(&ts_rs::Config::default()));s.push('\n');)*};}
    emit!(
        crate::game::Piece,
        Rules,
        Move,
        crate::game::Deck,
        crate::game::Respawn,
        crate::game::EndReason,
        crate::game::RoundEvent,
        crate::game::StepEvent,
        GameView,
        Settings,
        Player,
        Snapshot,
        Command,
        Reply,
        PreviewRequest,
        CardPreview,
        PreviewReply,
        crate::browser::Checkpoint,
        crate::browser::EngineRequest,
        crate::browser::EngineReply
    );
    s
}
